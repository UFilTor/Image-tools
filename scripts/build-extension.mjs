// Builds the "Send to Image Tools" browser extension (public/extension/) from lib/bookmarklet.ts, so the
// extension and the bookmarklet share one set of photo rules. Run it after changing that file:
//
//   npm run build:extension
//       writes public/extension/ for the live site (Image Tools zips that folder for "Get the extension")
//   node scripts/build-extension.mjs --origin http://localhost:3000 --out <folder>
//       writes a complete copy that sends to a local dev server (for testing)
//
// Generated: manifest.json, config.js, collect.js. Hand-written: background.js, popup.*, icon.svg and
// the icon-*.png files rendered from it.
// __tests__/extension.test.ts fails when public/extension/ is out of date.

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
export const LIVE_ORIGIN = "https://image-tools-understory-vibers.vercel.app";
const EXTENSION_DIR = path.join(ROOT, "public", "extension");
const HEADER = "// Generated by scripts/build-extension.mjs from lib/bookmarklet.ts. Do not edit.\n";

/** The generated files for an extension that sends to `origin`, by file name, and the names of the hand-written ones. */
export function extensionFiles(origin) {
  const source = fs.readFileSync(path.join(ROOT, "lib", "bookmarklet.ts"), "utf8");
  const js = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, removeComments: true },
  }).outputText;
  // Run in an empty context, so lib/bookmarklet.ts must not import anything (the bookmarklet and the
  // generated collect.js need it self-contained anyway).
  const mod = { exports: {} };
  vm.runInNewContext(js, { module: mod, exports: mod.exports });
  const { collectPhotoUrls, BOOKMARKLET_VERSION, EXTENSION_FILES } = mod.exports;

  const manifest = {
    manifest_version: 3,
    name: "Send to Image Tools",
    version: `1.${BOOKMARKLET_VERSION}`,
    description: "Downloads the images on the page you are looking at as they are, or sends them to Understory Image Tools.",
    action: {
      default_title: "Download or send this page's images",
      default_icon: { 16: "icon-16.png", 32: "icon-32.png" },
      default_popup: "popup.html",
    },
    icons: { 16: "icon-16.png", 32: "icon-32.png", 48: "icon-48.png", 128: "icon-128.png" },
    background: { service_worker: "background.js", type: "module" },
    // activeTab: the clicked page only, and only on click. downloads: saving originals into a site
    // folder. The host permission lets the extension hand the photos to the Image Tools tab it opens.
    permissions: ["activeTab", "scripting", "downloads"],
    host_permissions: [`${origin}/*`],
  };

  const generated = {
    "manifest.json": `${JSON.stringify(manifest, null, 2)}\n`,
    "config.js": `${HEADER}export const IMAGE_TOOLS = ${JSON.stringify(origin)};\nexport const VERSION = ${BOOKMARKLET_VERSION};\n`,
    "collect.js": `${HEADER}export const collectPhotoUrls = ${collectPhotoUrls.toString()};\n`,
  };
  return { generated, handWritten: EXTENSION_FILES.filter((name) => !(name in generated)) };
}

function main() {
  const args = process.argv.slice(2);
  const option = (name) => {
    const i = args.indexOf(name);
    return i === -1 ? undefined : args[i + 1];
  };
  const origin = option("--origin") ?? LIVE_ORIGIN;
  const out = path.resolve(option("--out") ?? EXTENSION_DIR);
  fs.mkdirSync(out, { recursive: true });
  const { generated, handWritten } = extensionFiles(origin);
  for (const [name, text] of Object.entries(generated)) fs.writeFileSync(path.join(out, name), text);
  if (out !== EXTENSION_DIR) {
    for (const name of handWritten) fs.copyFileSync(path.join(EXTENSION_DIR, name), path.join(out, name));
  }
  console.log(`Extension for ${origin} written to ${out}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
